#!/usr/bin/env bash
# =============================================================================================
#  Raspberry Pi 4B head unit setup  (Hudiy + themed offline nav + iPod + AM/FM + safe power)
#
#  Usage:  sudo ./setup.sh --vehicle f250|miata|frontier [--tier 1|2|3] [--region texas-plus|texas|us]
#                          [--user NAME] [--only 20-display,60-media] [--set KEY=VALUE ...] [--yes]
#
#  --set changes one setting in /etc/headunit/headunit.conf, e.g. switch from a bench monitor to
#  the car screen:  sudo /opt/headunit/setup.sh --set DISPLAY_TYPE=waveshare-7.9 --only 20-display
#
#  Safe to run more than once: every stage checks what's already done and only changes its own
#  marked blocks in system files. A full log goes to /var/log/headunit-setup.log.
#  Each stage is a short, readable script in setup.d/ -- read them before running if you like.
# =============================================================================================
set -euo pipefail
SRC_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$SRC_DIR/lib/common.sh"

VEHICLE="" TIER=2 REGION="" USER_NAME="${SUDO_USER:-}" ONLY="" YES=0 SETS=()
while [ $# -gt 0 ]; do
  case "$1" in
    --vehicle) VEHICLE=$2; shift 2;;
    --tier) TIER=$2; shift 2;;
    --region) REGION=$2; shift 2;;
    --user) USER_NAME=$2; shift 2;;
    --only) ONLY=$2; shift 2;;
    --set) [[ "$2" =~ ^[A-Z_][A-Z0-9_]*=[^\"\'\$\`]*$ ]] || die "--set needs KEY=VALUE (got '$2')"; SETS+=("$2"); shift 2;;
    --yes|-y) YES=1; shift;;
    -h|--help) sed -n '2,12p' "$0"; exit 0;;
    *) die "unknown option $1 (see --help)";;
  esac
done
[ "$(id -u)" -eq 0 ] || die "run with sudo"
[ -n "$USER_NAME" ] || USER_NAME=$(getent passwd 1000 | cut -d: -f1)
id "$USER_NAME" >/dev/null 2>&1 || die "user '$USER_NAME' not found (use --user)"
mkdir -p /etc/headunit; touch "$HU_LOG"

# 1) Install the package as a version folder, /opt/headunit-releases/<VERSION>, and point the
#    /opt/headunit symlink at it. (Software updates add new folders and swap the symlink.)
VER=$(cat "$SRC_DIR/VERSION" 2>/dev/null || echo 0.0.0)
REL_ROOT=/opt/headunit-releases
SRC_REAL=$(readlink -f "$SRC_DIR")
if [[ "$SRC_REAL" != "$REL_ROOT"/* ]]; then
  say "installing version $VER to $REL_ROOT/$VER"
  mkdir -p "$REL_ROOT/$VER"
  rsync -a --delete --exclude 'tools/node_modules' --exclude '.git' --exclude 'venv' --exclude 'out' "$SRC_DIR/" "$REL_ROOT/$VER/"
  SRC_REAL=$REL_ROOT/$VER
fi
if [ -d "$HU_ROOT" ] && [ ! -L "$HU_ROOT" ]; then      # older installs: /opt/headunit was a plain folder
  say "moving the old $HU_ROOT folder aside ($HU_ROOT.old)"
  rm -rf "$HU_ROOT.old"; mv "$HU_ROOT" "$HU_ROOT.old"
fi
if [ "$(readlink -f "$HU_ROOT" 2>/dev/null)" != "$SRC_REAL" ]; then
  ln -sfn "$SRC_REAL" "$HU_ROOT.new" && mv -T "$HU_ROOT.new" "$HU_ROOT"
fi
# 2) Write /etc/headunit/headunit.conf from the vehicle profile + tier.
if [ -n "$VEHICLE" ]; then
  [ -f "$HU_ROOT/config/$VEHICLE.conf" ] || die "no profile config/$VEHICLE.conf"
  source "$HU_ROOT/config/tiers.conf"
  vt="$(echo "$VEHICLE" | tr '[:lower:]' '[:upper:]')_TIER$TIER"
  tierline=${!vt:-}
  [ -n "$tierline" ] || tierline=$(eval echo "\$TIER$TIER")
  {
    echo "# Generated by setup.sh on $(date). Edit and re-run 'sudo /opt/headunit/setup.sh' to apply."
    echo "HU_USER=$USER_NAME"
    echo "TIER=$TIER"
    grep -vE '^\s*(#|$)' "$HU_ROOT/config/$VEHICLE.conf"
    for kv in $tierline; do echo "$kv"; done
    [ -n "$REGION" ] && echo "MAP_REGION=$REGION"
    echo "APP_DIR=$HU_ROOT/apps"
    echo "DATA_DIR=/var/lib/headunit"
  } | awk -F= '/^[A-Za-z_][A-Za-z0-9_]*=/ { last[$1] = NR } { line[NR] = $0; key[NR] = ($0 ~ /^[A-Za-z_][A-Za-z0-9_]*=/) ? $1 : "" }
      END { for (i = 1; i <= NR; i++) if (key[i] == "" || last[key[i]] == i) print line[i] }' > "$HU_CONF"
elif [ ! -f "$HU_CONF" ]; then
  die "first run needs --vehicle f250, miata or frontier"
fi
for kv in "${SETS[@]}"; do      # --set KEY=VALUE: replace the key or add it
  k=${kv%%=*}; sed -i "/^$k=/d" "$HU_CONF"; echo "$kv" >> "$HU_CONF"
done
say "vehicle: $(conf_get VEHICLE_NAME)  tier: $(conf_get TIER)  user: $(hu_user)  maps: $(conf_get MAP_REGION)"

if [ "$YES" -ne 1 ] && [ -t 0 ]; then
  read -r -p "Continue? [Y/n] " a; [[ "${a:-Y}" =~ ^[Yy] ]] || exit 0
fi

# 3) Run the stages in order.
for stage in "$HU_ROOT"/setup.d/[0-9]*.sh; do
  name=$(basename "$stage" .sh)
  if [ -n "$ONLY" ] && [[ ",$ONLY," != *",$name,"* ]]; then continue; fi
  say "---- $name"
  if ! bash "$stage" 2>&1 | tee -a "$HU_LOG"; then die "stage $name failed (see $HU_LOG)"; fi
done
say "setup complete. Reboot to start the head unit: sudo reboot"
